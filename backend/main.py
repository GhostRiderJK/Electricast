def _fold_label(test):
    start = pd.Timestamp(test["start"])
    end = pd.Timestamp(test["end"])
    if (start.year, start.month) == (end.year, end.month):
        return start.strftime("%b %Y")
    if start.year == end.year:
        return f"{start.strftime('%b')}\u2013{end.strftime('%b %Y')}"
    return f"{start.strftime('%b %Y')}\u2013{end.strftime('%b %Y')}"


def _mean_std(values):
    vals = [
        float(v) for v in values
        if v is not None and np.isfinite(v)
    ]
    if not vals:
        return {"mean": None, "std": None, "n": 0}
    std = float(np.std(vals, ddof=1)) if len(vals) > 1 else 0.0
    return {"mean": round(float(np.mean(vals)), 4),
            "std": round(std, 4), "n": len(vals)}


def _build_backtest_summary(results):
    folds = results["folds"]
    metric_names = ("MAE", "RMSE", "WAPE", "MASE", "R2", "sMAPE", "bias")
    model_names = list(folds[0]["models"])
    descriptions = {}
    descriptions.update(results.get("baseline_descriptions", {}))
    descriptions.update(results.get("learned_model_descriptions", {}))
    baselines = set(results.get("baselines", []))

    fold_meta = [
        {
            "id": fold["id"],
            "label": _fold_label(fold["test"]),
            "test_start": fold["test"]["start"],
            "test_end": fold["test"]["end"],
            "eval_hours": fold["test"]["eval_hours"],
            "eval_days": fold["test"]["eval_days"],
        }
        for fold in folds
    ]

    model_summaries = []
    for name in model_names:
        is_reference = name == "seasonal_naive_24"
        per_fold = []
        for fold in folds:
            metrics = fold["models"].get(name) or {"status": "no_data", "n": 0}
            seasonal = fold["models"].get("seasonal_naive_24") or {}
            ok = metrics.get("status") == "ok"
            seasonal_mae = seasonal.get("MAE") if seasonal.get("status") == "ok" else None
            beats = None
            if ok and not is_reference and metrics.get("MAE") is not None \
                    and seasonal_mae is not None:
                beats = bool(metrics["MAE"] < seasonal_mae)
            per_fold.append({
                "id": fold["id"],
                "status": metrics.get("status", "no_data"),
                "n": metrics.get("n", 0),
                **{metric: metrics.get(metric) for metric in metric_names},
                "beats_seasonal_naive": beats,
                "seasonal_naive_MAE": seasonal_mae,
            })

        stats = {
            metric: _mean_std([
                row[metric] for row in per_fold if row["status"] == "ok"
            ])
            for metric in metric_names
        }
        comparable = [
            row for row in per_fold
            if row["status"] == "ok" and row["seasonal_naive_MAE"] is not None
        ]
        folds_beaten = sum(
            1 for row in comparable if row["beats_seasonal_naive"] is True
        )
        beats_naive = None if is_reference else (
            folds_beaten > len(comparable) / 2 if comparable else None
        )

        model_summaries.append({
            "key": name,
            "label": BACKTEST_LABELS.get(name, name),
            "kind": "baseline" if name in baselines else "learned",
            "description": descriptions.get(name, ""),
            "is_reference": is_reference,
            "mean": {metric: stats[metric]["mean"] for metric in metric_names},
            "std": {metric: stats[metric]["std"] for metric in metric_names},
            "n_folds": stats["MAE"]["n"],
            "folds_beaten": folds_beaten,
            "comparable_folds": len(comparable),
            "beats_seasonal_naive": beats_naive,
            "per_fold": per_fold,
        })

    return {
        "generated_at": results.get("generated_at"),
        "protocol": results.get("protocol"),
        "beats_rule": (
            "lower MAE than seasonal naive in a majority of the folds where "
            "both models have data"
        ),
        "fold_order": [fold["id"] for fold in folds],
        "folds": fold_meta,
        "models": model_summaries,
    }


BACKTEST_MODEL_KEYS = ("xgboost", "sarima", "p50", "seasonal_naive")
BACKTEST_SERIES_KEYS = ("actual", "seasonal_naive", "xgboost", "sarima",
                        "p10", "p50", "p90")


def _mae(pairs):
    values = [abs(pred - actual) for actual, pred in pairs if pred is not None]
    return round(float(np.mean(values)), 2) if values else None


def _mean(values):
    values = [float(value) for value in values if value is not None]
    return round(float(np.mean(values)), 2) if values else None


def _model_error_summary(records, key):
    pairs = [
        (record["actual"], record.get(key))
        for record in records
        if record.get("actual") is not None and record.get(key) is not None
    ]
    return {"mae_wh": _mae(pairs), "n": len(pairs)}


def _day_payload(fold_id, fold_label, date, records):
    arrays = {key: [None] * 24 for key in BACKTEST_SERIES_KEYS}
    for record in records:
        hour = int(record["time"][11:13])
        for key in BACKTEST_SERIES_KEYS:
            arrays[key][hour] = record.get(key)

    actuals = [value for value in arrays["actual"] if value is not None]
    return {
        "date": date,
        "weekday": pd.Timestamp(date).day_name(),
        "fold_id": fold_id,
        "fold_label": fold_label,
        "labels": [f"{hour:02d}:00" for hour in range(24)],
        **arrays,
        "n_eval_hours": len(records),
        "actual_peak_wh": round(max(actuals), 2) if actuals else None,
        "actual_mean_wh": _mean(actuals),
        "model_mae": {
            key: _model_error_summary(records, key) for key in BACKTEST_MODEL_KEYS
        },
    }


def _build_backtest_dashboard(results):
    fold_meta = [
        {
            "id": fold["id"],
            "label": _fold_label(fold["test"]),
            "test_start": fold["test"]["start"],
            "test_end": fold["test"]["end"],
        }
        for fold in results["folds"]
    ]
    meta_by_id = {meta["id"]: meta for meta in fold_meta}

    days = []
    by_date = {}
    all_records = []
    for fold in results["folds"]:
        hourly = fold.get("hourly") or {"columns": [], "rows": []}
        columns = hourly.get("columns", [])
        records = [dict(zip(columns, row)) for row in hourly.get("rows", [])]
        BACKTEST_RECORDS[fold["id"]] = records
        grouped = {}
        for record in records:
            date = record["time"][:10]
            grouped.setdefault(date, []).append(record)
        all_records.extend(records)

        fold_days = []
        for date in sorted(grouped):
            payload = _day_payload(
                fold["id"], meta_by_id[fold["id"]]["label"], date, grouped[date]
            )
            by_date[date] = payload
            fold_days.append({
                "date": date,
                "weekday": payload["weekday"],
                "eval_hours": payload["n_eval_hours"],
                "actual_peak_wh": payload["actual_peak_wh"],
            })
        days.append({**meta_by_id[fold["id"]], "days": fold_days})

    by_hour = []
    for hour in range(24):
        rows = [record for record in all_records
                if int(record["time"][11:13]) == hour]
        by_hour.append({
            "hour": hour,
            "n": sum(1 for record in rows if record.get("actual") is not None),
            "models": {
                key: _model_error_summary(rows, key) for key in BACKTEST_MODEL_KEYS
            },
        })

    months = {}
    for record in all_records:
        month = int(record["time"][5:7])
        months.setdefault(month, []).append(record)
    by_month = [{
        "month": month,
        "label": MONTH_NAMES[month - 1],
        "n": sum(1 for record in months[month] if record.get("actual") is not None),
        "models": {
            key: _model_error_summary(months[month], key)
            for key in BACKTEST_MODEL_KEYS
        },
    } for month in sorted(months)]

    worst_days = [
        {
            "date": payload["date"],
            "weekday": payload["weekday"],
            "fold_label": payload["fold_label"],
            "n_eval_hours": payload["n_eval_hours"],
            "actual_peak_wh": payload["actual_peak_wh"],
            "models": payload["model_mae"],
        }
        for payload in by_date.values()
        if payload["model_mae"]["xgboost"]["mae_wh"] is not None
        and payload["n_eval_hours"] >= 12
    ]
    worst_days.sort(key=lambda day: day["models"]["xgboost"]["mae_wh"],
                    reverse=True)

    return (
        {"folds": days},
        by_date,
        {
            "by_hour": by_hour,
            "by_month": by_month,
            "worst_days": worst_days[:10],
            "ranking": "XGBoost MAE, minimum 12 evaluable hours",
        },
    )


def load_backtest():
    global BACKTEST_RESULTS, BACKTEST_SUMMARY, BACKTEST_DAYS, BACKTEST_DAY_INDEX
    global BACKTEST_ERRORS
    if os.path.exists(BACKTEST_PATH):
        with open(BACKTEST_PATH, "r") as f:
            results = json.load(f)
        BACKTEST_RESULTS = results
        BACKTEST_SUMMARY = _build_backtest_summary(results)
        BACKTEST_RECORDS.clear()
        BACKTEST_DAYS, BACKTEST_DAY_INDEX, BACKTEST_ERRORS = (
            _build_backtest_dashboard(results)
        )
        print(f"Loaded backtest summary from {BACKTEST_PATH}")
    else:
        print(f"{BACKTEST_PATH} not found. Run: python evaluate.py")


load_backtest()


