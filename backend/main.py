@app.get("/api/predictions/daily")
def get_daily_predictions(month: Optional[str] = Query(default=None)):
    if not DATA:
        return _no_data()
    daily = DATA["predictions"]["daily"]
    if month:
        indices = [i for i, lbl in enumerate(daily["labels"]) if lbl.startswith(month)]
        if not indices:
            return {"labels": [], "actual": [], "lstm": [], "sarima": [], "xgboost": []}
        return {
            "labels": [daily["labels"][i] for i in indices],
            "actual": [daily["actual"][i] for i in indices],
            "lstm": [daily["lstm"][i] for i in indices],
            "sarima": [daily["sarima"][i] for i in indices],
            "xgboost": [daily["xgboost"][i] for i in indices],
        }
    return daily


@app.get("/api/predictions/hourly")
def get_hourly_predictions(month: str = Query(default="Jan"),
                           day: int = Query(default=15)):
    if not DATA:
        return _no_data()

    month_num = None
    for i, mn in enumerate(MONTH_NAMES):
        if mn == month:
            month_num = i + 1
            break
    if month_num is None:
        return {"error": f"Unknown month: {month}"}

    target = f"-{month_num:02d}-{day:02d} "
    labels = DATA["predictions"]["hourly_labels"]
    indices = [i for i, lbl in enumerate(labels) if target in lbl]

    if not indices:
        return {"labels": [], "actual": [], "lstm": [], "sarima": [],
                "xgboost": [], "date": f"{month} {day}"}

    hour_labels = [labels[i].split(" ")[1] for i in indices]
    date_str = labels[indices[0]].split(" ")[0]

    return {
        "labels": hour_labels,
        "actual": [DATA["predictions"]["actual"][i] for i in indices],
        "lstm": [DATA["predictions"]["lstm"][i] for i in indices],
        "sarima": [DATA["predictions"]["sarima"][i] for i in indices],
        "xgboost": [DATA["predictions"]["xgboost"][i] for i in indices],
        "date": f"{month} {day}, {date_str[:4]}",
    }


